/**
 * Phonetic Normalizer: Normalizes Thanglish spelling variants BEFORE conversion
 * (e.g. boopathy / boobathi / boobathy -> boopathi -> பூபதி)
 */
function normalizeThanglishSpelling(raw) {
  let w = raw.toLowerCase().trim();

  // 1. Normalize ending variants (-thy, -thi, -by, -ti -> -thi)
  w = w.replace(/(thy|bathi|bathy|ti|ty)$/i, "thi");

  // 2. Normalize b/bh -> p (e.g. booba -> boopa)
  w = w.replace(/booba/g, "boopa").replace(/buba/g, "boopa").replace(/bhupa/g, "boopa");

  // 3. Normalize common clusters
  w = w.replace(/sozha/g, "சோழ").replace(/zha/g, "ழ");
  w = w.replace(/kaathu/g, "காது").replace(/kuththu/g, "குத்து").replace(/kuthu/g, "குத்து");
  w = w.replace(/keerthi/g, "கீர்த்தி").replace(/kirthi/g, "கீர்த்தி").replace(/keerthy/g, "கீர்த்தி");

  return w;
}

/**
 * Universal Phonetic Transliteration Engine (Thanglish -> Tamil)
 */
function transliterateThanglishToTamil(word) {
  if (!word) return "";
  
  // Master dictionary check first
  const masterMatch = masterDictionary.find((item) =>
    item.keys.some((k) => k.toLowerCase() === word.toLowerCase())
  );
  if (masterMatch) return masterMatch.ta;

  // Normalize spelling variations
  let w = normalizeThanglishSpelling(word);

  // If already replaced by cluster rule
  if (/[\u0B80-\u0BFF]/.test(w)) return w;

  let res = "";
  let i = 0;

  while (i < w.length) {
    let matched = false;

    // Try 4-char, 3-char, 2-char, 1-char combinations
    for (let len = 4; len >= 1; len--) {
      if (i + len <= w.length) {
        const sub = w.substr(i, len);
        if (uyirmeiMap[sub]) {
          res += uyirmeiMap[sub];
          i += len;
          matched = true;
          break;
        }
      }
    }

    if (!matched) {
      const c = w[i];
      if (i === w.length - 1 || !"aeiou".includes(w[i + 1])) {
        if (pulliMap[w.substr(i, 2)]) {
          res += pulliMap[w.substr(i, 2)];
          i += 2;
          continue;
        } else if (pulliMap[c]) {
          res += pulliMap[c];
          i++;
          continue;
        }
      }
      
      // Standalone Vowels
      if (c === "a") res += "அ";
      else if (c === "e") res += "எ";
      else if (c === "i") res += "இ";
      else if (c === "o") res += "ஒ";
      else if (c === "u") res += "உ";
      else res += c;
      i++;
    }
  }

  return res;
}

/**
 * Universal Phonetic Transliteration Engine (Tamil -> English)
 */
function transliterateTamilToEnglish(text) {
  if (!text) return "";
  
  const masterMatch = masterDictionary.find((item) =>
    item.keys.some((k) => k.toLowerCase() === text.trim().toLowerCase())
  );
  if (masterMatch) return masterMatch.en;

  return text
    .split(/(\s+|-)/)
    .map((part) => {
      if (part.trim() && !part.match(/^[\s-]+$/)) {
        return part.charAt(0).toUpperCase() + part.slice(1);
      }
      return part;
    })
    .join("");
}

/**
 * Convert user data text dynamically at display time (for ANY Thanglish variation)
 */
export function convertDataText(text, targetLang) {
  if (!text || typeof text !== "string") return text || "";
  const trimmed = text.trim();
  if (!trimmed) return "";

  // 1. Master Dictionary Match Check
  const masterMatch = masterDictionary.find((item) =>
    item.keys.some((k) => k.toLowerCase() === trimmed.toLowerCase())
  );
  if (masterMatch) {
    return targetLang === "ta" ? masterMatch.ta : masterMatch.en;
  }

  // 2. Token-by-token conversion (handles mixed strings like "பூபதி - keerthi" or "boopathy - kirthi")
  const tokens = trimmed.split(/(\s+|-)/);

  if (targetLang === "ta") {
    return tokens
      .map((tok) => {
        if (!tok.trim() || tok.match(/^[\s-]+$/)) return tok;
        
        // If token contains English letters, convert to Tamil!
        if (/[a-zA-Z]/.test(tok)) {
          const match = masterDictionary.find((item) =>
            item.keys.some((k) => k.toLowerCase() === tok.toLowerCase())
          );
          if (match) return match.ta;

          // Check spelling normalized variant
          const normTok = normalizeThanglishSpelling(tok);
          const normMatch = masterDictionary.find((item) =>
            item.keys.some((k) => k.toLowerCase() === normTok)
          );
          if (normMatch) return normMatch.ta;

          return transliterateThanglishToTamil(tok);
        }
        return tok;
      })
      .join("");
  } else {
    // Target is English
    return tokens
      .map((tok) => {
        if (!tok.trim() || tok.match(/^[\s-]+$/)) return tok;
        
        const match = masterDictionary.find((item) =>
          item.keys.some((k) => k.toLowerCase() === tok.toLowerCase())
        );
        if (match) return match.en;

        if (/[\u0B80-\u0BFF]/.test(tok)) {
          return transliterateTamilToEnglish(tok);
        }

        // Clean & capitalize Thanglish word (e.g. boopathy -> Boopathy)
        return tok.charAt(0).toUpperCase() + tok.slice(1);
      })
      .join("");
  }
}
